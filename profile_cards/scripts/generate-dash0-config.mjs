#!/usr/bin/env node
// Generates src/dash0-config.generated.ts for the Dash0 Web SDK (@dash0/sdk-web).
//
// Inputs (all optional, same variables the Flutter builds use):
//   OTLP_ENDPOINT                 Dash0 OTLP endpoint (a trailing /v1/<signal> is removed)
//   OTLP_HEADERS                  "Authorization=Bearer <token>,Dash0-Dataset=<dataset>"
//   DASH0_ENVIRONMENT             deployment.environment.name (sandbox | beta | production)
//   DASH0_DEPLOYMENT_NAME         defaults to "train-with-joe-<environment>"
//   DASH0_DEPLOYMENT_ID           e.g. "<run_id>-<run_attempt>"
//   DASH0_VCS_REVISION            commit SHA
//   DASH0_VCS_REF_NAME            branch or tag
//   DASH0_VCS_REPOSITORY_URL      repository URL
//
// When the endpoint or the bearer token is missing, a disabled config (null) is written,
// so local development and builds without secrets work and the SDK is never initialised.
// The Dash0 auth token ends up in the browser bundle. Use a token that is restricted to
// ingesting (public / web-SDK token), never an admin token.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function parseOtlpHeaders(raw) {
  const headers = {};
  if (!raw) return headers;
  for (const pair of raw.split(',')) {
    const idx = pair.indexOf('=');
    if (idx > 0) headers[pair.slice(0, idx).trim()] = pair.slice(idx + 1).trim();
  }
  return headers;
}

export function extractBearerToken(headers) {
  for (const [key, rawValue] of Object.entries(headers)) {
    if (key.toLowerCase() !== 'authorization') continue;
    let value = rawValue.trim();
    if (value.toLowerCase() === 'bearer') value = '';
    else if (value.toLowerCase().startsWith('bearer ')) value = value.slice(7).trim();
    return value || undefined;
  }
  return undefined;
}

export function extractDash0Dataset(headers) {
  for (const [key, value] of Object.entries(headers)) {
    if (key.toLowerCase() === 'dash0-dataset' && value.trim()) return value.trim();
  }
  return undefined;
}

export function normalizeOtlpEndpoint(endpoint) {
  let url = endpoint.trim().replace(/\/+$/, '');
  for (const signal of ['traces', 'logs', 'metrics']) {
    const suffix = `/v1/${signal}`;
    if (url.endsWith(suffix)) {
      url = url.slice(0, -suffix.length);
      break;
    }
  }
  return url;
}

export function buildConfig(env, deploymentPrefix) {
  const endpoint = normalizeOtlpEndpoint(env.OTLP_ENDPOINT ?? '');
  const headers = parseOtlpHeaders(env.OTLP_HEADERS ?? '');
  const authToken = extractBearerToken(headers);
  if (!endpoint || !authToken) return null;

  const environment = (env.DASH0_ENVIRONMENT ?? '').trim();
  const config = {
    endpointUrl: endpoint,
    authToken,
    dataset: extractDash0Dataset(headers),
    environment: environment || undefined,
    deploymentName:
      (env.DASH0_DEPLOYMENT_NAME ?? '').trim() ||
      (environment ? `${deploymentPrefix}-${environment}` : undefined),
    deploymentId: (env.DASH0_DEPLOYMENT_ID ?? '').trim() || undefined,
    vcsRevision: (env.DASH0_VCS_REVISION ?? '').trim() || undefined,
    vcsRefName: (env.DASH0_VCS_REF_NAME ?? '').trim() || undefined,
    vcsRepositoryUrl: (env.DASH0_VCS_REPOSITORY_URL ?? '').trim() || undefined,
  };
  return Object.fromEntries(Object.entries(config).filter(([, v]) => v !== undefined));
}

export function renderConfigFile(config) {
  return [
    '// Generated by scripts/generate-dash0-config.mjs. Do not edit or commit.',
    "import type { Dash0BuildConfig } from './dash0';",
    '',
    `export const dash0BuildConfig: Dash0BuildConfig | null = ${JSON.stringify(config, null, 2)};`,
    '',
  ].join('\n');
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  if (process.env.OTLP_HEADERS && !extractDash0Dataset(parseOtlpHeaders(process.env.OTLP_HEADERS))) {
    console.error(
      'OTLP_HEADERS is set but has no Dash0-Dataset= entry. Expected: Authorization=Bearer <token>,Dash0-Dataset=<dataset>',
    );
    process.exit(1);
  }
  const config = buildConfig(process.env, 'train-with-joe');
  const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/dash0-config.generated.ts');
  writeFileSync(out, renderConfigFile(config));
  console.log(
    config
      ? `Dash0 web SDK: enabled`
      : 'Dash0 web SDK: disabled (OTLP_ENDPOINT or the bearer token in OTLP_HEADERS is not set)',
  );
}
